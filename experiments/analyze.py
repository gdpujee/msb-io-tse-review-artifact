"""Turn raw per-instance results into the tables used in the paper.

Every table is written to results/tables as BOTH .csv and .md so the numbers in
the manuscript can always be traced to a file generated by this script.
"""
from __future__ import annotations

import argparse
import csv
import json
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from config import RESULTS_DIR  # noqa: E402
from stats_v2 import compare_methods, bootstrap_ci, holm_correct  # noqa: E402

TABLES = RESULTS_DIR / "tables"
TABLES.mkdir(parents=True, exist_ok=True)

# NOTE: per-instance rows use "ap" (see evaluate.Metrics.as_row) while the
# aggregate helper returns "map"; keep them distinct to avoid silent KeyErrors.
METRIC_COLS = ["hit@1", "hit@3", "hit@5", "hit@10", "hit@20", "hit@50", "mrr", "ap"]


def load(paths: list[Path]) -> list[dict]:
    rows = []
    for p in paths:
        for line in p.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if line:
                rows.append(json.loads(line))
    return rows


def mean(xs):
    return sum(xs) / len(xs) if xs else 0.0


def _sign_test_p(npos: int, n: int) -> float:
    """Two-sided exact binomial sign test, p=0.5 (self-implemented; no scipy)."""
    from math import comb
    if n == 0:
        return 1.0
    k = min(npos, n - npos)
    tail = sum(comb(n, i) for i in range(0, k + 1)) / (2 ** n)
    return min(1.0, 2 * tail)


def write_table(name: str, header: list[str], rows: list[list]):
    with (TABLES / f"{name}.csv").open("w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(header)
        w.writerows(rows)
    with (TABLES / f"{name}.md").open("w", encoding="utf-8") as f:
        f.write("| " + " | ".join(header) + " |\n")
        f.write("|" + "|".join(["---"] * len(header)) + "|\n")
        for r in rows:
            f.write("| " + " | ".join(str(x) for x in r) + " |\n")
    print(f"  wrote {TABLES}/{name}.csv + .md")


def main() -> None:
    global TABLES
    ap = argparse.ArgumentParser()
    ap.add_argument("inputs", nargs="+", type=Path)
    ap.add_argument("--methods", nargs="*", default=None)
    ap.add_argument("--table-dir", type=Path, default=RESULTS_DIR / "tables_v2")
    args = ap.parse_args()
    TABLES = args.table_dir
    TABLES.mkdir(parents=True, exist_ok=True)

    rows = load(args.inputs)
    methods = args.methods or sorted({r["method"] for r in rows})
    rows = [r for r in rows if r["method"] in methods]
    # reference method: plain BM25 whenever it is present, else the first one
    ref = "bm25" if "bm25" in methods else methods[0]
    print(f"loaded {len(rows)} rows | {len({r['instance_id'] for r in rows})} instances | "
          f"methods: {methods} | reference: {ref}")

    # ---- Table 1: per-language x method -------------------------------------
    print("\n[Table 1] per-language x method")
    header = ["lang", "n", "method"] + METRIC_COLS
    out = []
    for lang in sorted({r["lang"] for r in rows}):
        for m in methods:
            sub = [r for r in rows if r["lang"] == lang and r["method"] == m]
            if not sub:
                continue
            out.append([lang, len(sub), m] +
                       [round(mean([r[c] for r in sub]), 4) for c in METRIC_COLS])
    write_table("t1_lang_method", header, out)

    # ---- Table 2: overall x method ------------------------------------------
    print("\n[Table 2] overall x method")
    out = []
    for m in methods:
        sub = [r for r in rows if r["method"] == m]
        if not sub:
            continue
        vals = [r["hit@10"] for r in sub]
        ci = bootstrap_ci(vals)
        out.append([m, len(sub)] + [round(mean([r[c] for r in sub]), 4) for c in METRIC_COLS] +
                   [f"[{ci[0]:.3f},{ci[1]:.3f}]"])
    write_table("t2_overall_method", ["method", "n"] + METRIC_COLS + ["hit@10 95%CI"], out)

    # ---- Table 3: paired significance vs reference --------------------------
    if True:
        print(f"\n[Table 3] paired tests vs {ref}")
        allres = []
        for metric in ["hit@1", "hit@10", "mrr"]:
            others = [m for m in methods if m != ref]
            allres += compare_methods(rows, metric, ref, others, "lang")
            allres += compare_methods(rows, metric, ref, others, None)
        out = []
        for r in allres:
            out.append([r["group"] or "ALL", r["metric"], r["method"], r["n_paired"],
                        r["n_clusters"], r["test"], r["n_test_informative"],
                        r["mean_ref"], r["mean_method"], r["delta"],
                        r["delta_cluster_bootstrap_95ci"], r["p_instance"], r["p_cluster"],
                        r["p_cluster_holm"], r["n_cluster_informative"],
                        r["rank_biserial"], r["effect"],
                        "yes" if r["significant"] else "no"])
        write_table("t3_significance",
                    ["group", "metric", "method", "n_paired", "n_repos", "test",
                     "n_informative", "mean_ref", "mean_method", "delta", "delta_95ci",
                     "p_instance", "p_repo", "p_repo_holm", "n_repo_informative",
                     "rank_biserial", "effect", "sig"], out)

    # ---- Table 3b: cross-language consistency -------------------------------
    # Pooling all instances into one paired test is misleading: languages differ
    # hugely in base accuracy, and the sample is dominated by whichever
    # languages have most instances. Instead compute the paired delta *within*
    # each language, then ask how consistent its sign is across languages.
    print("\n[Table 3b] cross-language consistency of the effect")
    out = []
    for metric in ["hit@1", "hit@10", "mrr"]:
        for m in methods:
            if m == ref:
                continue
            deltas = []
            for lang in sorted({r["lang"] for r in rows}):
                a = {r["instance_id"]: r[metric] for r in rows
                     if r["lang"] == lang and r["method"] == ref}
                b = {r["instance_id"]: r[metric] for r in rows
                     if r["lang"] == lang and r["method"] == m}
                ks = sorted(set(a) & set(b))
                if len(ks) < 10:
                    continue
                deltas.append((lang, len(ks), sum(b[k] - a[k] for k in ks) / len(ks)))
            if len(deltas) < 3:
                continue
            npos = sum(1 for _, _, d in deltas if d > 0)
            nneg = sum(1 for _, _, d in deltas if d < 0)
            ntie = len(deltas) - npos - nneg
            n_nonzero = npos + nneg
            out.append([metric, m, len(deltas), n_nonzero, npos, nneg, ntie,
                        round(_sign_test_p(npos, n_nonzero), 4),
                        round(sum(d for _, _, d in deltas) / len(deltas), 4),
                        "; ".join(f"{l}:{d:+.3f}" for l, _, d in deltas)])
    write_table("t3b_cross_language",
                ["metric", "method", "n_langs", "n_nonzero", "n_positive", "n_negative", "n_ties",
                 "sign_test_p", "mean_lang_delta", "per_language"], out)

    # ---- Table 3c: matched component ablations -----------------------------
    print("\n[Table 3c] matched component ablations")
    matched = [
        ("bm25", "bm25_path", "path-text weighting"),
        ("bm25", "anchor_path_only", "explicit path cue"),
        ("bm25", "anchor_symbol_only", "symbol cue"),
        ("bm25", "bm25_graph", "graph over BM25"),
        ("bm25_anchor", "bm25_anchor_graph", "graph over both cues"),
        ("anchor_path_only", "anchor_path_graph", "graph over path cue"),
    ]
    out = []
    available = set(methods)
    for metric in ("hit@1", "hit@10", "mrr"):
        metric_results = []
        for base, treatment, component in matched:
            if base not in available or treatment not in available:
                continue
            for result in compare_methods(rows, metric, base, [treatment], None):
                metric_results.append((base, treatment, component, result))
        adjusted = holm_correct([item[3]["p_cluster"] for item in metric_results])
        for (base, treatment, component, result), p_holm in zip(metric_results, adjusted):
            out.append([metric, component, base, treatment, result["n_paired"],
                        result["n_clusters"], result["test"], result["delta"],
                        result["delta_cluster_bootstrap_95ci"], result["p_instance"],
                        result["p_cluster"], p_holm, result["rank_biserial"]])
    write_table("t3c_matched_ablation",
                ["metric", "component", "base", "treatment", "n", "n_repos", "test",
                 "delta", "delta_95ci", "p_instance", "p_repo", "p_repo_holm",
                 "rank_biserial"], out)

    # ---- Table 3d: shortcut/cue stratification -----------------------------
    print("\n[Table 3d] effect stratified by explicit gold-path cue")
    out = []
    for metric in ("hit@1", "hit@10", "mrr"):
        for method in methods:
            if method == ref:
                continue
            for cue in (False, True):
                sub = [row for row in rows if bool(row.get("query_mentions_gold_path")) == cue]
                for result in compare_methods(sub, metric, ref, [method], None):
                    out.append([metric, method, "present" if cue else "absent",
                                result["n_paired"], result["n_clusters"], result["delta"],
                                result["delta_cluster_bootstrap_95ci"], result["p_instance"],
                                result["p_cluster"],
                                result["rank_biserial"]])
    write_table("t3d_path_cue_strata",
                ["metric", "method", "gold_path_cue", "n", "n_repos", "delta",
                 "delta_95ci", "p_instance", "p_repo", "rank_biserial"], out)

    # ---- Table 7: micro vs repo-balanced (macro) language aggregate ---------
    # Measured on C: between-repository difficulty variance is far larger than
    # between-method variance, and repositories are very unevenly sampled across
    # languages (e.g. ponyc alone is 64% of the C instances). A plain micro
    # average over instances therefore confounds "language" with "which repos
    # happen to be in the split". We report both.
    print("\n[Table 7] micro vs repo-balanced (macro) language aggregate")
    out = []
    for lang in sorted({r["lang"] for r in rows}):
        for m in methods:
            sub = [r for r in rows if r["lang"] == lang and r["method"] == m]
            if not sub:
                continue
            by_repo: dict[str, list[dict]] = defaultdict(list)
            for r in sub:
                by_repo[r["repo"]].append(r)
            micro = {c: mean([r[c] for r in sub]) for c in METRIC_COLS}
            # macro = mean over repositories of the per-repository mean
            macro = {c: mean([mean([r[c] for r in v]) for v in by_repo.values()])
                     for c in METRIC_COLS}
            out.append([lang, m, len(sub), len(by_repo)] +
                       [round(micro[c], 4) for c in ("hit@1", "hit@10", "mrr")] +
                       [round(macro[c], 4) for c in ("hit@1", "hit@10", "mrr")] +
                       [round(macro[c] - micro[c], 4) for c in ("hit@1", "hit@10", "mrr")])
    write_table("t7_micro_vs_macro",
                ["lang", "method", "n_inst", "n_repos",
                 "micro_hit@1", "micro_hit@10", "micro_mrr",
                 "macro_hit@1", "macro_hit@10", "macro_mrr",
                 "diff_hit@1", "diff_hit@10", "diff_mrr"], out)

    # ---- Table 8: does repository size moderate the effect? (RQ3) -----------
    # Buckets are defined on n_files (candidate set size) pooled over all
    # languages and all methods, so boundaries do not depend on the metric.
    print("\n[Table 8] effect of method by repository-size bucket")
    sizes = sorted(r["n_files"] for r in rows)
    if sizes:
        q1 = sizes[len(sizes) // 3]
        q2 = sizes[2 * len(sizes) // 3]

        def bucket(n):
            return "small" if n <= q1 else ("medium" if n <= q2 else "large")

        out = []
        for b in ("small", "medium", "large"):
            for m in methods:
                sub = [r for r in rows if r["method"] == m and bucket(r["n_files"]) == b]
                if not sub:
                    continue
                rng = (f"<={q1}" if b == "small" else (f"{q1+1}-{q2}" if b == "medium" else f">{q2}"))
                out.append([b, rng, m, len(sub)] +
                           [round(mean([r[c] for r in sub]), 4)
                            for c in ("hit@1", "hit@10", "mrr")])
        write_table("t8_size_buckets",
                    ["bucket", "n_files_range", "method", "n", "hit@1", "hit@10", "mrr"], out)

    # ---- Table 4: per-repository (difficulty varies a lot) ------------------
    print("\n[Table 4] per-repository (reference method only)")
    out = []
    for (lang, repo), sub in sorted({(r["lang"], r["repo"]): 0 for r in rows}.items()):
        s = [r for r in rows if r["lang"] == lang and r["repo"] == repo and r["method"] == ref]
        if not s:
            continue
        out.append([lang, repo, len(s), round(mean([r["n_files"] for r in s]), 0),
                    round(mean([r["hit@1"] for r in s]), 3),
                    round(mean([r["hit@10"] for r in s]), 3),
                    round(mean([r["mrr"] for r in s]), 3)])
    write_table("t4_per_repo", ["lang", "repo", "n", "avg_files", "hit@1", "hit@10", "mrr"], out)

    # ---- Table 5: data-definition accounting (RQ4) -------------------------
    print("\n[Table 5] gold-set accounting (RQ4)")
    out = []
    for lang in sorted({r["lang"] for r in rows}):
        sub = [r for r in rows if r["lang"] == lang and r["method"] == ref]
        if not sub:
            continue
        n = len(sub)
        out.append([lang, n,
                    sum(r["n_gold_all"] for r in sub),
                    sum(r["n_gold_evaluable"] for r in sub),
                    sum(r["n_gold_excluded"] for r in sub),
                    round(1 - (sum(r["n_gold_evaluable"] for r in sub) /
                               max(1, sum(r["n_gold_all"] for r in sub))), 3),
                    sum(r["no_evaluable_gold"] for r in sub),
                    round(mean([r["n_gold_all"] for r in sub]), 2)])
    write_table("t5_gold_accounting",
                ["lang", "n_inst", "gold_files_all", "gold_evaluable", "gold_excluded",
                 "frac_excluded", "inst_without_evaluable_gold", "avg_gold_per_inst"], out)

    # ---- Table 5b: explicit evaluation-protocol sensitivity ---------------
    print("\n[Table 5b] protocol sensitivity")
    out = []
    for lang in sorted({row["lang"] for row in rows}):
        for method in methods:
            sub = [row for row in rows if row["lang"] == lang and row["method"] == method]
            if not sub:
                continue
            conditional = [row for row in sub if not row["no_evaluable_gold"]]
            out.append([
                lang, method, len(sub), len(conditional),
                round(mean([row["hit@1"] for row in sub]), 4),
                round(mean([row["hit@1"] for row in conditional]), 4),
                round(mean([row["all_hit@1"] for row in sub]), 4),
                round(mean([row["mrr"] for row in sub]), 4),
                round(mean([row["mrr"] for row in conditional]), 4),
                round(mean([row["ap"] for row in sub]), 4),
                round(mean([row["reachable_ap"] for row in conditional]), 4),
            ])
    write_table("t5b_protocol_sensitivity",
                ["lang", "method", "n_all", "n_candidate_present", "any_hit1_unconditional",
                 "any_hit1_conditional", "all_target_hit1", "mrr_unconditional",
                 "mrr_conditional", "ap_all_gold", "ap_reachable_gold_conditional"], out)

    # ---- Table 6: cost ------------------------------------------------------
    print("\n[Table 6] runtime cost")
    out = []
    for m in methods:
        sub = [r for r in rows if r["method"] == m and "secs" in r]
        if not sub:
            continue
        out.append([m, len(sub), round(mean([r["secs"] for r in sub]), 3),
                    round(max(r["secs"] for r in sub), 2),
                    0.0])
    write_table("t6_cost", ["method", "n", "mean_secs_per_instance", "max_secs", "api_cost_usd"], out)

    print("\nDONE")


if __name__ == "__main__":
    main()
